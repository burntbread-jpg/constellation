alter table public.health_alert_events
  add column if not exists resolved_at timestamptz,
  add column if not exists resolved_by uuid,
  add column if not exists resolution_summary text;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'health_alert_events_resolution_summary_length'
      and conrelid = 'public.health_alert_events'::regclass
  ) then
    alter table public.health_alert_events
      add constraint health_alert_events_resolution_summary_length
      check (resolution_summary is null or char_length(resolution_summary) between 5 and 500);
  end if;
end
$$;

create index if not exists health_alert_events_open_idx
  on public.health_alert_events (created_at desc)
  where resolved_at is null;

create table if not exists public.health_alert_actions (
  id bigint generated by default as identity primary key,
  health_alert_event_id bigint not null references public.health_alert_events(id) on delete cascade,
  action text not null check (action in ('acknowledged','resolved','reopened')),
  actor_id uuid not null,
  note text not null check (char_length(note) between 5 and 500),
  created_at timestamptz not null default now()
);

create index if not exists health_alert_actions_event_created_idx
  on public.health_alert_actions (health_alert_event_id, created_at desc);

alter table public.health_alert_actions enable row level security;
drop policy if exists health_alert_actions_deny_client_access on public.health_alert_actions;
create policy health_alert_actions_deny_client_access
  on public.health_alert_actions for all to anon, authenticated
  using (false) with check (false);
revoke all on public.health_alert_actions from anon, authenticated;
grant all on public.health_alert_actions to service_role;

create or replace function public.record_health_alert_action(
  p_alert_id bigint,
  p_action text,
  p_actor_id uuid,
  p_note text
)
returns jsonb
language plpgsql
security invoker
set search_path = pg_catalog, public
as $$
declare
  alert public.health_alert_events%rowtype;
  action_name text;
  acted_at timestamptz := now();
begin
  p_note := btrim(coalesce(p_note, ''));
  if p_action not in ('acknowledge', 'resolve', 'reopen') then
    raise exception 'invalid alert action';
  end if;
  if char_length(p_note) < 5 or char_length(p_note) > 500 then
    raise exception 'invalid alert action note';
  end if;

  select * into alert
  from public.health_alert_events
  where id = p_alert_id
  for update;
  if not found then raise exception 'alert not found'; end if;

  if p_action = 'acknowledge' then
    if alert.acknowledged_at is not null or alert.resolved_at is not null then
      raise exception 'invalid alert transition';
    end if;
    update public.health_alert_events
      set acknowledged_at = acted_at, acknowledged_by = p_actor_id, resolution_note = p_note
      where id = p_alert_id;
    action_name := 'acknowledged';
  elsif p_action = 'resolve' then
    if alert.acknowledged_at is null or alert.resolved_at is not null then
      raise exception 'invalid alert transition';
    end if;
    update public.health_alert_events
      set resolved_at = acted_at, resolved_by = p_actor_id, resolution_summary = p_note
      where id = p_alert_id;
    action_name := 'resolved';
  else
    if alert.resolved_at is null then raise exception 'invalid alert transition'; end if;
    update public.health_alert_events
      set acknowledged_at = null, acknowledged_by = null, resolution_note = null,
          resolved_at = null, resolved_by = null, resolution_summary = null
      where id = p_alert_id;
    action_name := 'reopened';
  end if;

  insert into public.health_alert_actions (health_alert_event_id, action, actor_id, note, created_at)
  values (p_alert_id, action_name, p_actor_id, p_note, acted_at);

  return jsonb_build_object(
    'id', p_alert_id,
    'action', action_name,
    'actedAt', acted_at,
    'acknowledged', p_action <> 'reopen',
    'resolved', p_action = 'resolve'
  );
end
$$;

revoke all on function public.record_health_alert_action(bigint, text, uuid, text) from public, anon, authenticated;
grant execute on function public.record_health_alert_action(bigint, text, uuid, text) to service_role;
