create table if not exists public.ai_editorial_ab_runs (
  id bigint generated by default as identity primary key,
  name text not null,
  model text not null,
  target_work_count smallint not null check (target_work_count between 30 and 50),
  status text not null default 'collecting' check (status in ('collecting', 'reviewing', 'promoted', 'rejected')),
  min_pass_rate numeric(5,4) not null default 0.80 check (min_pass_rate between 0 and 1),
  max_spoilers integer not null default 0 check (max_spoilers >= 0),
  min_preference_uplift numeric(5,4) not null default 0.05 check (min_preference_uplift between 0 and 1),
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  promoted_at timestamptz
);

create table if not exists public.ai_editorial_ab_items (
  id bigint generated by default as identity primary key,
  run_id bigint not null references public.ai_editorial_ab_runs(id) on delete cascade,
  work_id text not null,
  title text not null,
  media_type text not null check (media_type in ('ANIME', 'FILM', 'TV', 'BOOK', 'MANGA', 'OTHER')),
  work_json jsonb not null,
  control_text text not null,
  candidate_text text,
  candidate_outcome text not null default 'pending',
  machine_pass boolean not null default false,
  candidate_first boolean not null default false,
  generated_at timestamptz,
  created_at timestamptz not null default now(),
  unique (run_id, work_id)
);

create table if not exists public.ai_editorial_ab_reviews (
  id bigint generated by default as identity primary key,
  item_id bigint not null references public.ai_editorial_ab_items(id) on delete cascade,
  reviewer_id text not null,
  quality_pass boolean not null,
  spoiler boolean not null default false,
  preference text not null check (preference in ('control', 'candidate', 'tie')),
  control_score smallint not null check (control_score between 1 and 5),
  candidate_score smallint not null check (candidate_score between 1 and 5),
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (item_id, reviewer_id)
);

create index if not exists ai_editorial_ab_runs_status_idx on public.ai_editorial_ab_runs(status, created_at desc);
create index if not exists ai_editorial_ab_items_run_idx on public.ai_editorial_ab_items(run_id, id);
create index if not exists ai_editorial_ab_reviews_item_idx on public.ai_editorial_ab_reviews(item_id);

alter table public.ai_editorial_ab_runs enable row level security;
alter table public.ai_editorial_ab_items enable row level security;
alter table public.ai_editorial_ab_reviews enable row level security;

create policy ai_editorial_ab_runs_deny_client on public.ai_editorial_ab_runs for all to anon, authenticated using (false) with check (false);
create policy ai_editorial_ab_items_deny_client on public.ai_editorial_ab_items for all to anon, authenticated using (false) with check (false);
create policy ai_editorial_ab_reviews_deny_client on public.ai_editorial_ab_reviews for all to anon, authenticated using (false) with check (false);

revoke all on public.ai_editorial_ab_runs from anon, authenticated;
revoke all on public.ai_editorial_ab_items from anon, authenticated;
revoke all on public.ai_editorial_ab_reviews from anon, authenticated;
grant select, insert, update, delete on public.ai_editorial_ab_runs to service_role;
grant select, insert, update, delete on public.ai_editorial_ab_items to service_role;
grant select, insert, update, delete on public.ai_editorial_ab_reviews to service_role;
grant usage, select on all sequences in schema public to service_role;
