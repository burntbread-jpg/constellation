create table if not exists public.duplicate_work_merges (
  id bigint generated by default as identity primary key,
  target_work_id text not null,
  removed_work_id text not null,
  target_snapshot jsonb not null,
  removed_snapshot jsonb not null,
  merged_fields jsonb not null,
  impact jsonb not null default '{}'::jsonb,
  merged_by text not null,
  merged_at timestamptz not null default now()
);

create index if not exists duplicate_work_merges_target_idx
  on public.duplicate_work_merges(target_work_id, merged_at desc);

alter table public.duplicate_work_merges enable row level security;
revoke all on public.duplicate_work_merges from anon, authenticated;
grant all on public.duplicate_work_merges to service_role;

create or replace function public.merge_duplicate_works(
  p_target_id text,
  p_duplicate_id text,
  p_fields jsonb,
  p_reviewer_id text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_target public.works%rowtype;
  v_duplicate public.works%rowtype;
  v_work_json jsonb;
  v_archive_count integer := 0;
  v_connection_count integer := 0;
  v_feedback_count integer := 0;
  v_report_count integer := 0;
  v_audit_id bigint;
begin
  if p_target_id is null or p_duplicate_id is null or p_target_id = p_duplicate_id then
    raise exception 'distinct work ids are required';
  end if;

  select * into v_target from public.works where id = p_target_id for update;
  select * into v_duplicate from public.works where id = p_duplicate_id for update;
  if not found or v_target.id is null or v_duplicate.id is null then
    raise exception 'work not found';
  end if;

  select count(*) into v_archive_count from public.archive_items where work_id = p_duplicate_id;
  select count(*) into v_connection_count from public.connections where from_work_id = p_duplicate_id or to_work_id = p_duplicate_id;
  select count(*) into v_feedback_count from public.recommendation_feedback where from_work_id = p_duplicate_id or to_work_id = p_duplicate_id;
  select count(*) into v_report_count from public.metadata_reports where work_id = p_duplicate_id;

  update public.works set
    title = coalesce(nullif(p_fields->>'title',''), v_target.title),
    original_title = nullif(p_fields->>'original_title',''),
    creator = coalesce(nullif(p_fields->>'creator',''), v_target.creator),
    release_year = case when (p_fields->>'release_year') ~ '^\d{4}$' then (p_fields->>'release_year')::integer else null end,
    media_type = coalesce(nullif(p_fields->>'media_type',''), v_target.media_type),
    poster_url = nullif(p_fields->>'poster_url',''),
    description = coalesce(p_fields->>'description',''),
    source = coalesce(nullif(p_fields->>'source',''), v_target.source),
    canonical_key = nullif(p_fields->>'canonical_key',''),
    updated_at = now()
  where id = p_target_id
  returning to_jsonb(works.*) into v_work_json;

  v_work_json := jsonb_build_object(
    'id', p_target_id,
    'title', v_work_json->>'title',
    'originalTitle', v_work_json->>'original_title',
    'creator', v_work_json->>'creator',
    'year', v_work_json->'release_year',
    'mediaType', v_work_json->>'media_type',
    'type', v_work_json->>'media_type',
    'posterUrl', v_work_json->>'poster_url',
    'description', v_work_json->>'description',
    'source', v_work_json->>'source',
    'canonicalKey', v_work_json->>'canonical_key'
  );

  insert into public.archive_items (
    user_id, work_id, work_json, rating, my_comment, ai_comment,
    analysis_status, analysis_json, archive_state, created_at, updated_at, taste_vector
  )
  select user_id, p_target_id, coalesce(work_json,'{}'::jsonb) || v_work_json,
    rating, my_comment, ai_comment, analysis_status, analysis_json,
    archive_state, created_at, updated_at, taste_vector
  from public.archive_items where work_id = p_duplicate_id
  on conflict (user_id, work_id) do update set
    work_json = coalesce(public.archive_items.work_json,'{}'::jsonb) || v_work_json,
    rating = coalesce(public.archive_items.rating, excluded.rating),
    my_comment = case when length(excluded.my_comment) > length(public.archive_items.my_comment) then excluded.my_comment else public.archive_items.my_comment end,
    ai_comment = case when length(excluded.ai_comment) > length(public.archive_items.ai_comment) then excluded.ai_comment else public.archive_items.ai_comment end,
    analysis_status = case when public.archive_items.analysis_status = 'completed' or excluded.analysis_status = 'completed' then 'completed' else public.archive_items.analysis_status end,
    analysis_json = coalesce(public.archive_items.analysis_json, excluded.analysis_json),
    archive_state = case when public.archive_items.archive_state = 'completed' or excluded.archive_state = 'completed' then 'completed' else public.archive_items.archive_state end,
    created_at = least(public.archive_items.created_at, excluded.created_at),
    updated_at = greatest(public.archive_items.updated_at, excluded.updated_at),
    taste_vector = coalesce(public.archive_items.taste_vector, excluded.taste_vector);

  update public.archive_items
  set work_json = coalesce(work_json,'{}'::jsonb) || v_work_json, updated_at = now()
  where work_id = p_target_id;

  insert into public.taste_tags(user_id,work_id,tag,category,score,evidence,engine,created_at)
  select user_id,p_target_id,tag,category,score,evidence,engine,created_at
  from public.taste_tags where work_id = p_duplicate_id
  on conflict (user_id,work_id,tag) do update set
    score = greatest(public.taste_tags.score, excluded.score),
    evidence = coalesce(public.taste_tags.evidence, excluded.evidence);

  insert into public.connections(user_id,from_work_id,to_work_id,connection_type,reason,score,shared_tags,work_json,created_at,updated_at)
  select distinct on (user_id,new_from,new_to,connection_type)
    user_id,new_from,new_to,connection_type,reason,score,shared_tags,
    case when to_work_id = p_duplicate_id then coalesce(work_json,'{}'::jsonb) || v_work_json else work_json end,
    created_at,updated_at
  from (
    select c.*, case when from_work_id=p_duplicate_id then p_target_id else from_work_id end new_from,
      case when to_work_id=p_duplicate_id then p_target_id else to_work_id end new_to
    from public.connections c where from_work_id=p_duplicate_id or to_work_id=p_duplicate_id
  ) moved
  where new_from <> new_to
  order by user_id,new_from,new_to,connection_type,score desc,updated_at desc
  on conflict (user_id,from_work_id,to_work_id,connection_type) do update set
    reason=excluded.reason, score=greatest(public.connections.score,excluded.score),
    shared_tags=excluded.shared_tags, work_json=excluded.work_json, updated_at=now();
  delete from public.connections where from_work_id=p_duplicate_id or to_work_id=p_duplicate_id;

  insert into public.recommendation_feedback(user_id,from_work_id,to_work_id,connection_mode,value,to_work_title_key,shared_tags,created_at,updated_at)
  select distinct on (user_id,new_from,new_to,connection_mode)
    user_id,new_from,new_to,connection_mode,value,
    case when to_work_id=p_duplicate_id then lower(regexp_replace(v_work_json->>'title','[^[:alnum:]]','','g')) else to_work_title_key end,
    shared_tags,created_at,updated_at
  from (
    select f.*, case when from_work_id=p_duplicate_id then p_target_id else from_work_id end new_from,
      case when to_work_id=p_duplicate_id then p_target_id else to_work_id end new_to
    from public.recommendation_feedback f where from_work_id=p_duplicate_id or to_work_id=p_duplicate_id
  ) moved
  where new_from <> new_to
  order by user_id,new_from,new_to,connection_mode,updated_at desc
  on conflict (user_id,from_work_id,to_work_id,connection_mode) do update set
    value=excluded.value, to_work_title_key=excluded.to_work_title_key,
    shared_tags=excluded.shared_tags, updated_at=now();
  delete from public.recommendation_feedback where from_work_id=p_duplicate_id or to_work_id=p_duplicate_id;

  update public.metadata_reports set work_id=p_target_id,
    work_title=v_work_json->>'title', canonical_key=v_work_json->>'canonicalKey'
  where work_id=p_duplicate_id;
  update public.metadata_changes set work_id=p_target_id, work_title=v_work_json->>'title'
  where work_id=p_duplicate_id;

  delete from public.archive_items where work_id=p_duplicate_id;
  delete from public.works where id=p_duplicate_id;

  insert into public.duplicate_work_merges(
    target_work_id,removed_work_id,target_snapshot,removed_snapshot,merged_fields,impact,merged_by
  ) values (
    p_target_id,p_duplicate_id,to_jsonb(v_target),to_jsonb(v_duplicate),p_fields,
    jsonb_build_object('archives',v_archive_count,'connections',v_connection_count,'feedback',v_feedback_count,'reports',v_report_count),
    p_reviewer_id
  ) returning id into v_audit_id;

  return jsonb_build_object(
    'audit_id',v_audit_id,'target_id',p_target_id,'removed_id',p_duplicate_id,
    'impact',jsonb_build_object('archives',v_archive_count,'connections',v_connection_count,'feedback',v_feedback_count,'reports',v_report_count)
  );
end;
$$;

revoke all on function public.merge_duplicate_works(text,text,jsonb,text) from public, anon, authenticated;
grant execute on function public.merge_duplicate_works(text,text,jsonb,text) to service_role;
