-- Stage 70: explicit privacy retention, atomic account-data deletion, and
-- bounded daily cleanup. All cleanup functions are server-only.
create extension if not exists pg_cron;

create table if not exists public.data_retention_runs (
  id bigint generated by default as identity primary key,
  policy_version smallint not null default 1 check (policy_version > 0),
  executed_at timestamptz not null default now(),
  cutoff_reference timestamptz not null,
  counts jsonb not null default '{}'::jsonb,
  duration_ms integer not null default 0 check (duration_ms >= 0)
);

create index if not exists data_retention_runs_executed_at_idx
  on public.data_retention_runs (executed_at desc);

alter table public.data_retention_runs enable row level security;
drop policy if exists data_retention_runs_deny_client_access on public.data_retention_runs;
create policy data_retention_runs_deny_client_access
  on public.data_retention_runs for all to anon, authenticated
  using (false) with check (false);
revoke all on public.data_retention_runs from public, anon, authenticated;
grant all on public.data_retention_runs to service_role;

create or replace function public.delete_user_private_data(p_user_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_archives integer;
  v_tags integer;
  v_connections integer;
  v_feedback integer;
  v_reports integer;
  v_profile integer;
begin
  if p_user_id is null then raise exception 'user id is required'; end if;

  select count(*) into v_archives from public.archive_items where user_id = p_user_id;
  select count(*) into v_tags from public.taste_tags where user_id = p_user_id;
  select count(*) into v_connections from public.connections where user_id = p_user_id;
  select count(*) into v_feedback from public.recommendation_feedback where user_id = p_user_id;
  select count(*) into v_reports from public.metadata_reports where user_id = p_user_id;

  delete from public.profiles where id = p_user_id;
  get diagnostics v_profile = row_count;

  if exists (select 1 from public.archive_items where user_id = p_user_id)
    or exists (select 1 from public.taste_tags where user_id = p_user_id)
    or exists (select 1 from public.connections where user_id = p_user_id)
    or exists (select 1 from public.recommendation_feedback where user_id = p_user_id)
    or exists (select 1 from public.metadata_reports where user_id = p_user_id) then
    raise exception 'private data deletion was incomplete';
  end if;

  return jsonb_build_object(
    'deleted', true,
    'profile', v_profile,
    'archives', v_archives,
    'tasteTags', v_tags,
    'connections', v_connections,
    'recommendationFeedback', v_feedback,
    'metadataReports', v_reports
  );
end;
$$;

revoke all on function public.delete_user_private_data(uuid) from public, anon, authenticated;
grant execute on function public.delete_user_private_data(uuid) to service_role;

create or replace function public.run_data_retention(
  p_now timestamptz default clock_timestamp(),
  p_batch_size integer default 5000
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_started timestamptz := clock_timestamp();
  v_batch integer := greatest(1, least(coalesce(p_batch_size, 5000), 20000));
  v_connections integer := 0;
  v_feedback integer := 0;
  v_reports integer := 0;
  v_changes integer := 0;
  v_merges integer := 0;
  v_alerts integer := 0;
  v_health integer := 0;
  v_buckets integer := 0;
  v_run_history integer := 0;
  v_cron_history integer := 0;
  v_run_id bigint;
  v_counts jsonb;
  v_duration integer;
begin
  with candidates as (
    select ctid from public.connections
    where updated_at < p_now - interval '180 days'
    order by updated_at limit v_batch for update skip locked
  ) delete from public.connections t using candidates c where t.ctid = c.ctid;
  get diagnostics v_connections = row_count;

  with candidates as (
    select ctid from public.recommendation_feedback
    where updated_at < p_now - interval '730 days'
    order by updated_at limit v_batch for update skip locked
  ) delete from public.recommendation_feedback t using candidates c where t.ctid = c.ctid;
  get diagnostics v_feedback = row_count;

  with candidates as (
    select ctid from public.metadata_reports
    where (status in ('accepted','rejected') and reviewed_at < p_now - interval '365 days')
       or (status = 'pending' and created_at < p_now - interval '180 days')
    order by created_at limit v_batch for update skip locked
  ) delete from public.metadata_reports t using candidates c where t.ctid = c.ctid;
  get diagnostics v_reports = row_count;

  with candidates as (
    select ctid from public.metadata_changes
    where report_id is null and status <> 'applying'
      and changed_at < p_now - interval '1095 days'
    order by changed_at limit v_batch for update skip locked
  ) delete from public.metadata_changes t using candidates c where t.ctid = c.ctid;
  get diagnostics v_changes = row_count;

  with candidates as (
    select ctid from public.duplicate_work_merges
    where restored_at < p_now - interval '1095 days'
    order by restored_at limit v_batch for update skip locked
  ) delete from public.duplicate_work_merges t using candidates c where t.ctid = c.ctid;
  get diagnostics v_merges = row_count;

  with candidates as (
    select ctid from public.health_alert_events
    where resolved_at < p_now - interval '365 days'
    order by resolved_at limit v_batch for update skip locked
  ) delete from public.health_alert_events t using candidates c where t.ctid = c.ctid;
  get diagnostics v_alerts = row_count;

  with candidates as (
    select r.ctid from public.health_check_runs r
    where r.checked_at < p_now - interval '90 days'
      and not exists (select 1 from public.health_alert_events e where e.health_check_run_id = r.id)
    order by r.checked_at limit v_batch for update of r skip locked
  ) delete from public.health_check_runs t using candidates c where t.ctid = c.ctid;
  get diagnostics v_health = row_count;

  with candidates as (
    select ctid from public.api_rate_limit_buckets
    where updated_at < p_now - interval '2 days'
    order by updated_at limit v_batch for update skip locked
  ) delete from public.api_rate_limit_buckets t using candidates c where t.ctid = c.ctid;
  get diagnostics v_buckets = row_count;

  with candidates as (
    select ctid from public.data_retention_runs
    where executed_at < p_now - interval '365 days'
    order by executed_at limit v_batch for update skip locked
  ) delete from public.data_retention_runs t using candidates c where t.ctid = c.ctid;
  get diagnostics v_run_history = row_count;

  if to_regclass('cron.job_run_details') is not null then
    execute format(
      'with candidates as (select ctid from cron.job_run_details where end_time < $1 - interval ''30 days'' order by end_time limit %s) delete from cron.job_run_details t using candidates c where t.ctid=c.ctid',
      v_batch
    ) using p_now;
    get diagnostics v_cron_history = row_count;
  end if;

  v_counts := jsonb_build_object(
    'connections', v_connections,
    'recommendationFeedback', v_feedback,
    'metadataReports', v_reports,
    'metadataChanges', v_changes,
    'restoredMergeAudits', v_merges,
    'resolvedHealthAlerts', v_alerts,
    'healthChecks', v_health,
    'rateLimitBuckets', v_buckets,
    'retentionRuns', v_run_history,
    'cronRuns', v_cron_history
  );
  v_duration := greatest(0, floor(extract(epoch from (clock_timestamp() - v_started)) * 1000)::integer);

  insert into public.data_retention_runs(policy_version, executed_at, cutoff_reference, counts, duration_ms)
  values (1, clock_timestamp(), p_now, v_counts, v_duration)
  returning id into v_run_id;

  return jsonb_build_object('runId', v_run_id, 'policyVersion', 1, 'counts', v_counts, 'durationMs', v_duration);
end;
$$;

revoke all on function public.run_data_retention(timestamptz, integer) from public, anon, authenticated;
grant execute on function public.run_data_retention(timestamptz, integer) to service_role;

do $schedule$
declare v_job_id bigint;
begin
  for v_job_id in select jobid from cron.job where jobname = 'taste-constellation-data-retention'
  loop
    perform cron.unschedule(v_job_id);
  end loop;
  perform cron.schedule(
    'taste-constellation-data-retention',
    '40 3 * * *',
    $job$select public.run_data_retention();$job$
  );
end;
$schedule$;

comment on function public.delete_user_private_data(uuid) is
  'Atomically deletes one Sites user profile and all cascading private Taste Constellation data.';
comment on function public.run_data_retention(timestamptz, integer) is
  'Applies privacy retention policy v1 in bounded batches and records aggregate deletion counts.';
